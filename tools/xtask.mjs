import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { root, models, checkout, sync, verifySnapshot } from "./sync-upstream.mjs";

const [command, ...args] = process.argv.slice(2);
const run = (program, argv) => execFileSync(program, argv, { cwd: root, stdio: "inherit" });
const option = (name, fallback) => args.includes(name) ? args[args.indexOf(name) + 1] : fallback;
const renderers = ["web", "ssr", "desktop", "mobile", "fullstack", "liveview", "native"];

function checkModels() {
  const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }));
  for (const pkg of metadata.packages.filter(pkg => models.includes(pkg.name))) {
    const features = metadata.resolve.nodes.find(node => node.id === pkg.id)?.features ?? [];
    if (features.some(feature => feature === "bare" || feature === "bindgen")) throw new Error(`${pkg.name} enables a forbidden feature: ${features.join(", ")}`);
  }
  for (const name of models) {
    const graph = execFileSync("cargo", ["tree", "-p", name, "--edges", "normal,build,features", "--locked"], { cwd: root, encoding: "utf8" });
    if (/wasm-bindgen|feature "(?:bare|bindgen)"/.test(graph)) throw new Error(`${name} enables a standalone WASM boundary`);
  }
  console.log("All eight upstream model dependency graphs are bindgen-free.");
}

function recordRenderers(results) {
  const report = { host: `${process.platform}/${process.arch}`, mobileTarget: process.env.FC_MOBILE_TARGET ?? "aarch64-apple-ios-sim", results };
  mkdirSync(join(root, "target"), { recursive: true });
  writeFileSync(join(root, "target/renderer-results.json"), JSON.stringify(report, null, 2) + "\n");
  const rows = renderers.map(renderer => `| ${renderer} | ${results[renderer] ?? "not run"} |`).join("\n");
  writeFileSync(join(root, "docs/RENDERERS.md"), `# Renderer build record\n\nGenerated by \`cargo xtask demo --renderer all --build-only\` on ${report.host}.\nMobile target: \`${report.mobileTarget}\`.\n\n| Configuration | Build |\n| --- | --- |\n${rows}\n\nFullstack builds both the server and wasm client. These are compilation results,\nnot claims that each renderer has passed a runtime accessibility review. The web\ndemo has the real Chrome suite in \`cargo xtask check\`; desktop/mobile/liveview/native\nruntime smoke tests, screen-reader passes, and fullstack hydration tests remain\nplanned. SSR exports and component structure are exercised by Rust tests.\n\nThe current static Divider uses native HTML and upstream border CSS on every host.\nDomBridge reports unsupported host APIs explicitly; native/SSR clipboard actions\nkeep selectable source text as their fallback. Modal and popover components do not\nyet ship, so no untested overlay fallback is advertised.\n\nStandalone web supports fixture/theme/direction query inputs. SSR exports accept\nthose same inputs explicitly. Fullstack currently starts with the default showcase\non both server and client to preserve hydration structure; request-aware routing\nis still planned. Mobile runtime verification requires a simulator or device and\nis separate from this build.\n`);
}

function demo(renderer, buildOnly) {
  if (renderer === "all") {
    const results = {};
    recordRenderers(results);
    for (const name of renderers) {
      try { demo(name, true); results[name] = "passed"; }
      catch (error) { results[name] = "failed"; recordRenderers(results); throw error; }
      recordRenderers(results);
    }
    return;
  }
  if (!renderers.includes(renderer)) throw new Error(`unknown renderer: ${renderer}`);
  if (!buildOnly && renderer !== "ssr") {
    const platforms = { web: "web", desktop: "desktop", mobile: "ios", fullstack: "web", liveview: "liveview", native: "desktop" };
    const extra = renderer === "native" ? ["--renderer", "native"] : renderer === "fullstack" ? ["--fullstack", "true"] : [];
    run("dx", ["serve", "--package", "fc-demo", "--platform", platforms[renderer], ...extra]);
    return;
  }
  if (renderer === "web") {
    run("dx", [buildOnly ? "build" : "serve", "--package", "fc-demo", "--platform", "web"]);
  } else if (renderer === "fullstack") {
    run("cargo", ["build", "-p", "fc-demo", "--no-default-features", "--features", "server"]);
    run("cargo", ["build", "-p", "fc-demo", "--no-default-features", "--features", "web,fullstack", "--target", "wasm32-unknown-unknown"]);
  } else {
    const target = renderer === "mobile" ? ["--target", process.env.FC_MOBILE_TARGET ?? "aarch64-apple-ios-sim"] : [];
    run("cargo", [buildOnly ? "build" : "run", "-p", "fc-demo", "--no-default-features", "--features", renderer, ...target]);
  }
}

try {
  switch (command) {
    case "sync-upstream": sync(args.includes("--check")); break;
    case "verify-snapshot": verifySnapshot(); break;
    case "demo": demo(option("--renderer", "web"), args.includes("--build-only")); break;
    case "browser": run("node", ["--test", "tests/browser/demo.test.mjs"]); break;
    case "models": {
      checkModels();
      for (const target of [[], ["--target", "wasm32-unknown-unknown"]]) run("cargo", ["check", "-p", "fc-dioxus", "--features", "web", "--locked", ...target]);
      console.log("Pinned model compatibility verified for native and wasm32.");
      break;
    }
    case "check":
      sync(true);
      run("cargo", ["fmt", "--all", "--", "--check"]);
      run("node", ["tools/architecture.mjs"]);
      checkModels();
      run("cargo", ["clippy", "--workspace", "--all-targets", "--locked", "--", "-D", "warnings"]);
      run("cargo", ["test", "--workspace", "--locked"]);
      run("cargo", ["test", "-p", "fc-dioxus", "--features", "testing", "--locked"]);
      run("cargo", ["run", "-p", "fc-a11y", "--", "check", "upstream/fixtures.html"]);
      run("cargo", ["build", "--workspace", "--target", "wasm32-unknown-unknown", "--locked"]);
      demo("all", true);
      run("node", ["--test", "tests/browser/demo.test.mjs"]);
      break;
    case "upstream-path": console.log(checkout()); break;
    default:
      console.log("cargo xtask sync-upstream [--check] | verify-snapshot | models | demo --renderer <web|ssr|desktop|mobile|fullstack|liveview|native|all> [--build-only] | browser | check");
      if (command && command !== "help") process.exitCode = 1;
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
