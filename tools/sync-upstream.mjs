import { execFileSync } from "node:child_process";
import { stripTypeScriptTypes } from "node:module";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pinText = readFileSync(join(root, "upstream.toml"), "utf8");
function pinValue(key) {
  const value = new RegExp(`^${key} = "([^"\\n]+)"$`, "m").exec(pinText)?.[1];
  if (!value) throw new Error(`missing upstream.${key}`);
  return value;
}
export const pin = { repo: pinValue("repo"), rev: pinValue("rev"), version: pinValue("css-version") };
/** Upstream bindings shipped as JavaScript: the editor and the modules it imports. */
export const bindings = ["editor", "selection", "urls", "toolbar"];
export const models = ["fc-core", "fc-model", "fc-rich-text", "fc-select", "fc-context-menu", "fc-grid", "fc-diff", "fc-git"];
if (!/^[0-9a-f]{40}$/.test(pin.rev) || pin.repo !== "https://github.com/rexlunae/future-css") {
  throw new Error("upstream must use the canonical repository and a full commit SHA");
}
export function files(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  }).sort();
}
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
function git(args, cwd) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }).trim();
}
export function checkout() {
  const cache = join(root, "target", "upstream", pin.rev);
  if (!existsSync(join(cache, ".git"))) {
    mkdirSync(cache, { recursive: true });
    git(["init", "--quiet"], cache);
    git(["remote", "add", "origin", pin.repo], cache);
    git(["fetch", "--depth=1", "origin", pin.rev], cache);
    git(["checkout", "--detach", "FETCH_HEAD"], cache);
  }
  if (git(["rev-parse", "HEAD"], cache) !== pin.rev || git(["status", "--porcelain", "--untracked-files=no"], cache)) {
    throw new Error(`upstream cache is not clean at the pin: ${cache}`);
  }
  return cache;
}

function generateTokens(tokens) {
  const entries = Object.entries(tokens).filter(([name]) => name.startsWith("--fc-")).sort(([a], [b]) => a.localeCompare(b, "en"));
  const variant = name => name.replace(/^--fc-/, "").split("-").map(s => s[0].toUpperCase() + s.slice(1)).join("");
  const names = entries.map(([name]) => variant(name));
  if (new Set(names).size !== names.length) throw new Error("token variant collision");
  const q = JSON.stringify;
  return `// Generated by cargo xtask sync-upstream. Do not edit.
use crate::Scheme;
/// Every token exported by the pinned upstream build.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
#[repr(usize)]
pub enum Token {
${entries.map(([name]) => `    /// CSS token ${name}.\n    ${variant(name)},`).join("\n")}
}
struct TokenData { name: &'static str, variable: &'static str, light: &'static str, dark: &'static str }
const DATA: &[TokenData] = &[
${entries.map(([name,v]) => `TokenData { name: ${q(name)}, variable: ${q(`var(${name})`)}, light: ${q(typeof v === "string" ? v : v.light)}, dark: ${q(typeof v === "string" ? v : v.dark)} },`).join("\n")}
];
impl Token {
    /// All tokens, in stable name order.
    pub const ALL: &'static [Self] = &[${names.map(n => `Self::${n}`).join(",")}];
    /// The CSS custom property name.
    #[must_use]
    pub fn name(self) -> &'static str { DATA.get(self as usize).map_or("", |data| data.name) }
    /// A CSS custom property reference.
    #[must_use]
    pub fn css_var(self) -> &'static str { DATA.get(self as usize).map_or("", |data| data.variable) }
    /// The upstream value before theme overrides.
    #[must_use]
    pub fn value(self, scheme: Scheme) -> &'static str {
        DATA.get(self as usize).map_or("", |data| match scheme { Scheme::Light => data.light, Scheme::Dark => data.dark })
    }
}
`;
}

export function sync(check = false) {
  const cache = checkout();
  execFileSync("npm", ["run", "build:css"], { cwd: cache, stdio: "inherit" });
  const version = JSON.parse(readFileSync(join(cache, "package.json"))).version;
  if (version !== pin.version) throw new Error(`css-version must be ${version}`);
  const expected = new Map();
  const manifestPath = "crates/fc-dioxus/Cargo.toml";
  const manifestText = readFileSync(join(root, manifestPath), "utf8");
  const modelBlock = /# BEGIN generated upstream models\n[\s\S]*?# END generated upstream models/;
  if (!modelBlock.test(manifestText)) throw new Error("model dependency generation markers are missing");
  expected.set(manifestPath, Buffer.from(manifestText.replace(modelBlock,
    "# BEGIN generated upstream models\n# Generated by cargo xtask sync-upstream; change upstream.toml instead.\n" +
    models.map(name => `${name} = { git = "${pin.repo}", rev = "${pin.rev}", default-features = false }`).join("\n") +
    "\n# END generated upstream models")));
  for (const path of files(join(cache, "dist")).filter(p => p.endsWith(".css"))) {
    expected.set(`crates/fc-dioxus/assets/${relative(join(cache, "dist"), path)}`, readFileSync(path));
  }
  for (const [source, dest] of [["dist/tokens.json", "tokens.json"], ["demo/fixtures.html", "fixtures.html"], ["src/js/theme-presets.ts", "theme-presets.ts"], ["LICENSE", "LICENSE"]]) {
    expected.set(`upstream/${dest}`, readFileSync(join(cache, source)));
  }
  // Bindings whose work is DOM interaction upstream keeps out of its Rust models,
  // shipped as upstream wrote them: types stripped, sibling imports pointed at .js.
  for (const name of bindings) {
    const source = readFileSync(join(cache, "src/js", `${name}.ts`), "utf8");
    const code = stripTypeScriptTypes(source, { mode: "strip" }).replace(/(from\s+"\.\/[a-z-]+)\.ts"/g, '$1.js"');
    expected.set(`crates/fc-dioxus/assets/js/${name}.js`, Buffer.from(code));
  }
  const tokenCode = generateTokens(JSON.parse(expected.get("upstream/tokens.json")));
  const formattedTokens = execFileSync("rustfmt", ["--edition", "2021", "--emit", "stdout"], { input: tokenCode });
  expected.set("crates/fc-tokens/src/generated.rs", formattedTokens);
  const cssPaths = [...expected.keys()].filter(p => p.endsWith(".css"));
  let assets = "// Generated by cargo xtask sync-upstream. Do not edit.\nuse dioxus::prelude::*;\n";
  for (const path of cssPaths) {
    const assetPath = path.replace("crates/fc-dioxus", "");
    const name = assetPath.replace("/assets/", "").replace(/\.css$/, "").replace(/[^a-zA-Z0-9]/g, "_").toUpperCase() + "_CSS";
    assets += `/// Upstream's ${assetPath.replace("/assets/", "")} stylesheet.\npub const ${name}: Asset = asset!(${JSON.stringify(assetPath)});\n`;
  }
  assets += `/// Upstream's DOM bindings, as one folder so their relative imports resolve.\npub const BINDINGS_JS: Asset = asset!("/assets/js", AssetOptions::folder());\n`;
  assets += `/// Upstream's declared CSS version.\npub const CSS_VERSION: &str = ${JSON.stringify(pin.version)};\n`;
  expected.set("crates/fc-dioxus/src/core/assets.rs", execFileSync("rustfmt", ["--edition", "2021", "--emit", "stdout"], { input: assets }));
  const manifest = { upstream: pin, files: Object.fromEntries([...expected].map(([p, b]) => [p, hash(b)])) };
  expected.set("upstream/manifest.json", Buffer.from(JSON.stringify(manifest, null, 2) + "\n"));
  const generated = ["crates/fc-dioxus/assets", "upstream"].flatMap(p => files(join(root, p)).map(p => relative(root, p)));
  const extra = generated.filter(p => !expected.has(p));
  if (check) {
    const changed = [...expected].filter(([p, bytes]) => !existsSync(join(root, p)) || !readFileSync(join(root, p)).equals(bytes)).map(([p]) => p);
    if (changed.length || extra.length) throw new Error(`generated files drifted; run cargo xtask sync-upstream:\n${[...changed, ...extra].join("\n")}`);
    console.log(`Verified ${expected.size} generated files against ${pin.rev}.`);
  } else {
    for (const path of extra) rmSync(join(root, path));
    for (const [path, bytes] of expected) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), bytes);
    }
    console.log(`Synced ${expected.size} generated files from ${pin.rev}.`);
  }
}

export function verifySnapshot() {
  const manifest = JSON.parse(readFileSync(join(root, "upstream/manifest.json")));
  if (JSON.stringify(manifest.upstream) !== JSON.stringify(pin)) throw new Error("upstream pin and snapshot disagree");
  for (const [path, digest] of Object.entries(manifest.files)) {
    if (!existsSync(join(root, path)) || hash(readFileSync(join(root, path))) !== digest) throw new Error(`generated file changed: ${path}`);
  }
  const extras = ["upstream", "crates/fc-dioxus/assets"].flatMap(p => files(join(root, p)))
    .map(p => relative(root, p)).filter(p => p !== "upstream/manifest.json" && !(p in manifest.files));
  if (extras.length) throw new Error(`untracked generated files: ${extras.join(", ")}`);
}
